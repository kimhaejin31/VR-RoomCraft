namespace VRRoomCraft.Data.Materials
{
    /// <summary>
    /// Defines all surface target types supported by VR RoomCraft.
    /// Used for matching material items to environment surface slots
    /// and filtering options in the VR Material Menu.
    /// </summary>
    public enum SurfaceType
    {
        None = 0,
        Wall = 1,
        Floor = 2,
        Ceiling = 3,
        KitchenCabinet = 4,
        Door = 5
    }
}
